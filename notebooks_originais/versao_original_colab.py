import os
import requests

API_KEY = "SUA_CHAVE_AQUI"  # removida; a versão nova lê de XENO_CANTO_API_KEY
DESTINO_BASE = "/content/drive/MyDrive/TFinal IA/audios"
LIMITE_POR_ESPECIE = 100
QUALIDADES = ["A", "B"]

ESPECIES = {
    "canario-da-horta": ("Sicalis", "flaveola"),
    "sabia-do-campo": ("Mimus", "saturninus"),
    "trinca-ferro": ("Saltator", "similis")
}

def ja_existe(destino, rec_id):
    return any(f.startswith(f"{rec_id}_") for f in os.listdir(destino))

def baixar_audios(especie_nome, gen, sp):
    destino = os.path.join(DESTINO_BASE, especie_nome)
    os.makedirs(destino, exist_ok=True)

    for qualidade in QUALIDADES:
        pagina = 1
        while True:
            if len(os.listdir(destino)) >= LIMITE_POR_ESPECIE:
                break

            query = f"gen:{gen}+sp:{sp}+cnt:Brazil+type:song+q:{qualidade}"
            url = f"https://xeno-canto.org/api/3/recordings?query={query}&page={pagina}&key={API_KEY}"
            print(f"\nBuscando {especie_nome} [q:{qualidade}] - página {pagina}")
            res = requests.get(url)
            dados = res.json()
            gravacoes = dados.get("recordings", [])
            if not gravacoes:
                break

            for rec in gravacoes:
                if len(os.listdir(destino)) >= LIMITE_POR_ESPECIE:
                    break

                try:
                    rec_id = rec["id"]
                    duracao = rec.get("length", "0:00")
                    minutos, segundos = map(int, duracao.split(":"))
                    dur_total = minutos * 60 + segundos
                    if dur_total < 5:
                        continue

                    if ja_existe(destino, rec_id):
                        continue

                    audio_url = rec["file"]
                    nome_arquivo = f"{rec_id}_{rec['gen']}_{rec['sp']}.mp3"
                    caminho = os.path.join(destino, nome_arquivo)

                    print(f"Baixando: {nome_arquivo} ({dur_total}s)")
                    audio_data = requests.get(audio_url).content
                    with open(caminho, "wb") as f:
                        f.write(audio_data)

                except Exception as e:
                    print(f"Erro ao baixar {rec.get('id', '??')}: {e}")

            if dados.get("numPages") and pagina >= int(dados["numPages"]):
                break
            pagina += 1

    print(f"Finalizado {especie_nome}: {len(os.listdir(destino))} arquivos na pasta.")

# para especies que ainda nao tem audios suficientes
for especie, (gen, sp) in ESPECIES.items():
    baixar_audios(especie, gen, sp)

from pydub import AudioSegment
import os
import math

especie = "trinca-ferro"
input_folder = f"/content/drive/MyDrive/TFinal IA/audios/{especie}"
output_folder = f"/content/drive/MyDrive/TFinal IA/trechos/{especie}"
os.makedirs(output_folder, exist_ok=True)

segment_duration_ms = 5000
silence_thresh_db = -40 # silencio minimo
min_dbfs_valid = -50 # evita trechos com ruído quase inaudível

# processar audio
def processar_audio(arquivo):
    caminho = os.path.join(input_folder, arquivo)

    try:
        audio = AudioSegment.from_file(caminho)
        audio = audio.set_channels(1).set_frame_rate(22050)
        duracao_total = len(audio)
        num_segmentos = math.ceil(duracao_total / segment_duration_ms)

        for i in range(num_segmentos):
            inicio = i * segment_duration_ms
            fim = min(inicio + segment_duration_ms, duracao_total)
            segmento = audio[inicio:fim]

            # descartar trechos silenciosos ou com ruído
            if segmento.dBFS < silence_thresh_db or segmento.dBFS < min_dbfs_valid:
                continue

            nome_base = os.path.splitext(arquivo)[0]
            nome_saida = f"{nome_base}_seg{i+1}.wav"
            caminho_saida = os.path.join(output_folder, nome_saida)
            segmento.export(caminho_saida, format="wav")
            print(f"Salvo: {nome_saida}")

    except Exception as e:
        print(f"Erro ao processar {arquivo}: {e}")

# processa todos os audios
for arquivo in os.listdir(input_folder):
    if arquivo.endswith(".mp3"):
        processar_audio(arquivo)

