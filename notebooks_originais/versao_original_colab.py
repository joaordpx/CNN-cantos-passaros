output_folder = f"/content/drive/MyDrive/TFinal IA/espectrogramas/{especie}"
os.makedirs(output_folder, exist_ok=True)

figsize = (4, 4)
dpi = 100
min_duracao_segundos = 1

def gerar_espectrograma(arquivo):
    caminho = os.path.join(input_folder, arquivo)

    try:
        y, sr = librosa.load(caminho, sr=22050)

        if len(y) < sr * min_duracao_segundos:
            print(f"Ignorado (muito curto): {arquivo}")
            return

        S = librosa.feature.melspectrogram(y=y, sr=sr, n_mels=128)
        S_dB = librosa.power_to_db(S, ref=np.max)

        plt.figure(figsize=figsize)
        librosa.display.specshow(S_dB, sr=sr, cmap='magma')
        plt.axis('off')

        nome_saida = arquivo.replace(".wav", ".png")
        caminho_saida = os.path.join(output_folder, nome_saida)
        plt.savefig(caminho_saida, bbox_inches='tight', pad_inches=0, dpi=dpi)
        plt.close()
        print(f"Salvo: {nome_saida}")

    except Exception as e:
        print(f"Erro ao processar {arquivo}: {e}")

for arquivo in os.listdir(input_folder):
    if arquivo.endswith(".wav"):
        gerar_espectrograma(arquivo)

